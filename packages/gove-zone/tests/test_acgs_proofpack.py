def test_tampered_receipt_with_rehashed_evidence_still_fails(tmp_path: Path) -> None:
    """The stronger attacker: edit the receipt AND recompute every evidence digest.

    Integrity then looks intact — the inner receipt-hash binding must catch it.
    """
    pack = _copy_golden(tmp_path)
    _edit_json(pack / RECEIPT_FILE, lambda d: d.__setitem__("actor", "attacker"))
    _rehash_evidence(pack)
    result = verify_pack(pack, now_iso=NOW_ISO)
    assert not result.valid
    assert result.integrity_status == "intact"  # digests recomputed by the attacker
    assert "RECEIPT_HASH_MISMATCH" in result.reasons


def test_tampered_chain_with_rehashed_evidence_still_fails(tmp_path: Path) -> None:
    pack = _copy_golden(tmp_path)

    def _flip(doc: dict[str, Any]) -> None:
        h = doc["events"][0]["event_hash"]
        doc["events"][0]["event_hash"] = ("0" if h[0] != "0" else "f") + h[1:]

    _edit_json(pack / AUDIT_CHAIN_FILE, _flip)
    _rehash_evidence(pack)
    result = verify_pack(pack, now_iso=NOW_ISO)
    assert not result.valid
    assert "AUDIT_CHAIN_BROKEN" in result.reasons


