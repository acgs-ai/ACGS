def _generate_golden(dest: Path) -> None:
    generate_proof_pack(
        dest,
        receipt_path=INPUTS / "receipts" / "r1.json",
        audit_path=INPUTS / "audit.jsonl",
        policy_bundle=INPUTS / "policy_bundle.json",
        side_store=INPUTS / "replay_side_store.jsonl",
        now_iso=NOW_ISO,
    )


def _copy_golden(tmp_path: Path) -> Path:
    dest = tmp_path / "pack"
    shutil.copytree(GOLDEN, dest)
    return dest


def _rehash_evidence(pack: Path) -> None:
    """Recompute the evidence digests after a tamper — the stronger attacker."""
    evidence = json.loads((pack / EVIDENCE_FILE).read_text(encoding="utf-8"))
    for name in ARTIFACT_FILES:
        data = (pack / name).read_bytes()
        evidence["artifacts"][name] = {
            "sha256": hashlib.sha256(data).hexdigest(),
            "bytes": len(data),
        }
    (pack / EVIDENCE_FILE).write_text(
        json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def _edit_json(path: Path, mutate: Any) -> None:
    doc = json.loads(path.read_text(encoding="utf-8"))
    mutate(doc)
    path.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8")


# --- 1. byte-golden generation -------------------------------------------------


def test_golden_bundle_regenerates_byte_identical(tmp_path: Path) -> None:
    fresh = tmp_path / "regen"
    _generate_golden(fresh)
    fresh_names = sorted(p.name for p in fresh.iterdir())
    golden_names = sorted(p.name for p in GOLDEN.iterdir())
    assert fresh_names == golden_names == sorted([EVIDENCE_FILE, *ARTIFACT_FILES])
    for name in fresh_names:
        assert (fresh / name).read_bytes() == (GOLDEN / name).read_bytes(), (
            f"{name}: regenerated bytes differ from the committed golden — if the "
            "format change is intentional, re-run fixtures/_generate_acgs_proofpack.py "
            "and review the diff"
        )


def test_generated_bundle_forces_lf_at_every_text_write(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Keep proof-pack bytes stable when the host defaults to CRLF."""
    fresh = tmp_path / "regen"
    original_write_text = Path.write_text
    observed: dict[str, str | None] = {}

    def _record_write_text(
        path: Path,
        data: str,
        encoding: str | None = None,
        errors: str | None = None,
        newline: str | None = None,
    ) -> int:
        if path.is_relative_to(fresh):
            observed[path.relative_to(fresh).as_posix()] = newline
        return original_write_text(path, data, encoding=encoding, errors=errors, newline=newline)

    monkeypatch.setattr(Path, "write_text", _record_write_text)
    _generate_golden(fresh)

    expected = sorted([EVIDENCE_FILE, *ARTIFACT_FILES])
    assert sorted(observed) == expected
    assert set(observed.values()) == {"\n"}
    for name in expected:
        payload = (fresh / name).read_bytes()
        assert b"\r" not in payload, f"{name}: unexpected CR/CRLF line ending"
        assert payload.endswith(b"\n"), f"{name}: missing terminal LF"


