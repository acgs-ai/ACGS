def test_replay_reverification_rejects_tampered_side_store(tmp_path: Path) -> None:
    side = tmp_path / "side.jsonl"
    entries = [
        json.loads(line)
        for line in (INPUTS / "replay_side_store.jsonl").read_text(encoding="utf-8").splitlines()
    ]
    entries[0]["args"]["path"] = "tampered.txt"
    side.write_text(
        "".join(
            json.dumps(e, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n"
            for e in entries
        ),
        encoding="utf-8",
    )
    result = verify_pack(
        GOLDEN, now_iso=NOW_ISO, policy_bundle=INPUTS / "policy_bundle.json", side_store=side
    )
    assert not result.valid
    assert result.replay_status == "failed"
    assert PackRejectionReason.REPLAY_MISMATCH in result.reasons


