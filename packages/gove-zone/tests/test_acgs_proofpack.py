def test_cli_generate_then_verify_roundtrip(tmp_path: Path, capsys: Any) -> None:
    out = tmp_path / "pack"
    rc = acgs_main(
        [
            "proofpack",
            "generate",
            "--receipt",
            str(INPUTS / "receipts" / "r1.json"),
            "--audit",
            str(INPUTS / "audit.jsonl"),
            "--out",
            str(out),
            "--now-iso",
            NOW_ISO,
        ]
    )
    assert rc == 0
    summary = json.loads(capsys.readouterr().out)
    assert summary["status"] == "pass"
    assert sorted(summary["files"]) == sorted([EVIDENCE_FILE, *ARTIFACT_FILES])

    rc = acgs_main(["proofpack", "verify", str(out), "--now-iso", NOW_ISO])
    assert rc == 0
    report = json.loads(capsys.readouterr().out)
    assert report["valid"] is True
    assert report["integrity_status"] == "intact"


